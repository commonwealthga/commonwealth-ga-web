/**
 * Canonical identity of the site, for search engines and link previews.
 *
 * One origin, in one place: canonical URLs, Open Graph images and the sitemap
 * must agree, and a relative `og:image` is silently ignored by every unfurler
 * (Discord included, which is how most people will first see a link to us).
 */
export const SITE_ORIGIN = 'https://commonwealth.ydns.eu';
export const SITE_NAME = 'The Commonwealth';
export const SITE_TAGLINE = 'a Global Agenda community server';

/** Where else this project lives — the same list every `sameAs` and link uses. */
export const DISCORD_URL = 'https://discord.gg/CqACf4qArk';
export const REPO_URL = 'https://github.com/kithanakodah/cw-globalagenda-ksp';

/**
 * The site itself and who runs it, as schema.org nodes.
 *
 * Emitted on every page: an assistant or a crawler that lands on any single page
 * should be able to tell what this site is and what it is about without crawling
 * the rest of it. `@id`s let the page's own nodes point back at them.
 */
export function siteSchema() {
	const organization = {
		'@type': 'Organization',
		'@id': `${SITE_ORIGIN}/#organization`,
		name: SITE_NAME,
		url: `${SITE_ORIGIN}/`,
		description: 'A volunteer-run Global Agenda community server: free to play, level 50 with everything unlocked, PvE and PvP every night.',
		logo: {
			'@type': 'ImageObject',
			url: `${SITE_ORIGIN}/og/home.jpg`,
			width: 1200,
			height: 630
		},
		sameAs: [DISCORD_URL, REPO_URL]
	};

	const website = {
		'@type': 'WebSite',
		'@id': `${SITE_ORIGIN}/#website`,
		name: SITE_NAME,
		alternateName: 'Commonwealth Global Agenda server',
		url: `${SITE_ORIGIN}/`,
		inLanguage: 'en-GB',
		publisher: { '@id': `${SITE_ORIGIN}/#organization` }
	};

	return [website, organization];
}

/** A trail for a detail page: Home › Section › This entry. */
export function breadcrumbSchema(trail: { name: string; path: string }[]) {
	return {
		'@type': 'BreadcrumbList',
		itemListElement: trail.map((item, index) => ({
			'@type': 'ListItem',
			position: index + 1,
			name: item.name,
			item: `${SITE_ORIGIN}${item.path}`
		}))
	};
}
/**
 * The image every page falls back to, and the cards that replace it.
 *
 * A single og.jpg meant a /builds link and an /events link unfurled identically.
 * These are generated by `scripts/og.sh` — same fonts, same palette, one per
 * section — and choosing by route here keeps every page from having to remember
 * which file it owns.
 */
export const OG_IMAGE = '/og.jpg';

/**
 * Bumped whenever the cards are re-rendered.
 *
 * Unfurlers cache the image by its URL — Discord in particular will keep showing
 * the card it first fetched — so a new design at the same path is invisible to
 * every link already shared. The query string makes each set a new URL.
 */
const OG_CARD_VERSION = 2;

const OG_CARDS: Record<string, string> = {
	'/': '/og/home.jpg',
	'/play': '/og/play.jpg',
	'/server': '/og/server.jpg',
	'/events': '/og/events.jpg',
	'/guides': '/og/guides.jpg',
	'/builds': '/og/builds.jpg',
	'/news': '/og/news.jpg',
	'/missions': '/og/missions.jpg',
	'/agents': '/og/agents.jpg',
	'/leaderboard': '/og/leaderboard.jpg',
	'/community': '/og/community.jpg',
	'/roadmap': '/og/roadmap.jpg'
};

/** The card for a pathname, matching on the first segment (`/guides/12-x` → guides). */
export function ogImageFor(pathname: string): string {
	const card =
		OG_CARDS[pathname] ?? OG_CARDS['/' + pathname.split('/').filter(Boolean)[0]] ?? OG_IMAGE;
	return `${card}?v=${OG_CARD_VERSION}`;
}
